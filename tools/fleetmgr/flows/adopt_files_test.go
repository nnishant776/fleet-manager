func goldenFacts(host string, previous map[string][]byte) machineFacts {
	return machineFacts{
		Host: host, Platform: "x86_64-linux", Boot: "uefi", Loader: "systemd-boot", Backend: "networkmanager",
		Timezone: "Europe/Berlin", Locale: "en_US.UTF-8", StateVersion: "24.11", Role: "workstation", MachineType: "laptop",
		Accounts: goldenAccounts, HardwareConfig: goldenHardware, Previous: previous,
	}
}

func checkGolden(t *testing.T, dir string, files map[string][]byte) {
	t.Helper()
	root := filepath.Join(goldenRoot, "config", "hosts", dir)
	if os.Getenv("FLEETMGR_UPDATE_GOLDEN") != "" {
		_ = os.RemoveAll(root)
		if err := writeHostFolder(root, files); err != nil {
			t.Fatal(err)
		}
		return
	}
	for _, p := range sortedPaths(files) {
		want, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
		if err != nil {
			t.Fatalf("%v: run the test with FLEETMGR_UPDATE_GOLDEN=1, check the files, and commit them", err)
		}
		if string(want) != string(files[p]) {
			t.Errorf("%s/%s differs from what the generator writes now: run the test with FLEETMGR_UPDATE_GOLDEN=1, check the diff, and commit it", dir, p)
		}
	}
	n := 0
	_ = filepath.WalkDir(root, func(_ string, d os.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			n++
		}
		return err
	})
	if n != len(files) {
		t.Errorf("%s holds %d files, the generator writes %d", dir, n, len(files))
	}
}

func TestTheSkeletonIsTheGoldenOne(t *testing.T) {
	files, err := adoptFiles(goldenFacts("laptop1", map[string][]byte{"configuration.nix": []byte("{ }\n")}), goldenSettings, false)
	if err != nil {
		t.Fatal(err)
	}
	checkGolden(t, "laptop1", files)
}

func TestTheCopiedConfigurationIsTheGoldenOne(t *testing.T) {
	files, err := adoptFiles(goldenFacts("laptop2", map[string][]byte{
		"configuration.nix":          []byte(goldenConfiguration),
		"hardware-configuration.nix": []byte(goldenHardware),
	}), goldenSettings, true)
	if err != nil {
		t.Fatal(err)
	}
	checkGolden(t, "laptop2", files)
}

func TestSignersFromClimbsOutOfTheHostsFolder(t *testing.T) {
	for dir, want := range map[string]string{
		"hosts":        "../../fleet/allowed_signers",
		"config/hosts": "../../../fleet/allowed_signers",
		"a/b/c/":       "../../../../fleet/allowed_signers",
	} {
		if got := signersFrom(dir); got != want {
			t.Errorf("signersFrom(%q) = %q, want %q", dir, got, want)
		}
	}
}

func TestAFullNameCannotBreakOutOfItsString(t *testing.T) {
	out := skeletonDefault(goldenFacts("laptop1", nil), goldenSettings)
	if !strings.Contains(out, `fullName = "Bob \"the builder\" \${x}";`) {
		t.Fatalf("the name is not escaped:\n%s", out)
	}
}

func TestGrubOnBiosNamesItsDevice(t *testing.T) {
	f := goldenFacts("laptop1", nil)
	f.Boot, f.Loader, f.GrubDevice = "bios", "grub", "/dev/disk/by-id/ata-DISK"
	if out := skeletonDefault(f, goldenSettings); !strings.Contains(out, `boot.loader.grub.device = "/dev/disk/by-id/ata-DISK";`) {
		t.Fatalf("no device:\n%s", out)
	}
}

func TestPreviousFilesMustStayInsideTheirFolder(t *testing.T) {
	for _, p := range []string{"../etc/passwd", "/etc/passwd", "a/../../b"} {
		if _, err := adoptFiles(goldenFacts("laptop1", map[string][]byte{p: nil}), goldenSettings, false); err == nil {
			t.Errorf("%q was taken", p)
		}
	}
}

func TestCopyingNeedsAConfigurationToImport(t *testing.T) {
	if _, err := adoptFiles(goldenFacts("laptop2", map[string][]byte{"flake.nix": nil}), goldenSettings, true); err == nil {
		t.Fatal("copied a folder with no configuration.nix")
	}
}

// server1 is the skeleton's other branches: BIOS with GRUB, networkd, a
// headless server, and an account with no password.
func TestTheBiosSkeletonIsTheGoldenOne(t *testing.T) {
	f := goldenFacts("server1", map[string][]byte{"configuration.nix": []byte("{ }\n")})
	f.Boot, f.Loader, f.GrubDevice = "bios", "grub", "/dev/disk/by-id/ata-QEMU_HARDDISK_QM00001"
	f.Backend, f.Role, f.MachineType = "networkd", "server", "headless"
	f.Accounts = []machineAccount{{Name: "ops", Full: "Operations", Privileged: true, Keys: true}}
	f.HardwareConfig = strings.Replace(goldenHardware, "  fileSystems.\"/boot\" =\n    { device = \"/dev/disk/by-uuid/1A2B-3C4D\";\n      fsType = \"vfat\";\n      options = [ \"fmask=0077\" \"dmask=0077\" ];\n    };\n\n", "", 1)
	files, err := adoptFiles(f, goldenSettings, false)
	if err != nil {
		t.Fatal(err)
	}
	checkGolden(t, "server1", files)
}

// desk1 is a new host: the disk layout on, no hardware-configuration.nix.
func TestTheNewHostIsTheGoldenOne(t *testing.T) {
	f := goldenFacts("desk1", nil)
	f.StateVersion, f.Role, f.MachineType = "26.05", "developer", "desktop"
	doc := newHostDefault(f, newHostDisk{Device: "/dev/nvme0n1", Encrypt: true}, goldenSettings)
	checkGolden(t, "desk1", map[string][]byte{"default.nix": []byte(doc)})
}
